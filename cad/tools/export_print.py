"""Build every part through the pipeline and write print-ready files to print/:
  print/<part>.stl, print/<part>.3mf (geometry in print orientation, mm), print/views/<part>.png,
  print/README.md (settings table generated from each part's PRINT dict + diagnostics verdict).
Fails (exit 1) if any part does not PASS. Usage: python cad/tools/export_print.py [part ...]
"""
import json
import shutil
import sys
from pathlib import Path

import trimesh

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "cad" / "tools"))
from pipeline import build, load_module  # noqa: E402

PARTS = ["moon_shell", "moon_base", "moon_ring", "pack_front", "pack_back", "pack_clip", "button_caps", "jig_led_board",
         "coupon_fit", "coupon_bayonet_cup", "coupon_bayonet_skirt", "coupon_litho_wedge"]
QTY = {"button_caps": "1 plate (3 caps)"}


def main(parts):
    out = ROOT / "print"
    (out / "views").mkdir(parents=True, exist_ok=True)
    rows, failed = [], []
    for name in PARTS:                           # README always lists every part
        src = ROOT / "cad" / "parts" / f"{name}.py"
        work = ROOT / "out" / name
        if name in parts:
            rc = build(src, work, views=True)
            diag = json.loads((work / "diagnostics.json").read_text())
            if rc != 0:
                failed.append(name)
                continue
            m = trimesh.load(work / f"{name}.stl")
            shutil.copy(work / f"{name}.stl", out / f"{name}.stl")
            m.export(out / f"{name}.3mf")
            shutil.copy(work / "views" / "shaded_iso.png", out / "views" / f"{name}.png")
        else:                                    # not rebuilt this run: keep its last exported result
            if not (work / "diagnostics.json").exists() or not (out / f"{name}.stl").exists():
                failed.append(name)
                continue
            diag = json.loads((work / "diagnostics.json").read_text())
        P = load_module(src).PRINT
        warns = [c["name"] for c in diag["checks"] if c["severity"] == "warn"]
        rows.append((name, P["material"], P["process"], P.get("supports", "none"),
                     ", ".join(f"{k}={v}" for k, v in P.get("slicer_overrides", {}).items()) or "-",
                     f"{diag['bounds'][1][0] - diag['bounds'][0][0]:.1f} x {diag['bounds'][1][1] - diag['bounds'][0][1]:.1f} x "
                     f"{diag['bounds'][1][2] - diag['bounds'][0][2]:.1f}", diag["verdict"], ", ".join(warns) or "-",
                     QTY.get(name, "1")))
    lines = ["# Print-ready files", "",
             "Generated by `python cad/tools/export_print.py` from `cad/parts/*.py` (every part builds **PASS** through the",
             "3dprint-contract checks: watertight, walls, overhangs/bridges, bed fit, clearances, part claims).",
             "Geometry is already in print orientation: **do not auto-orient**. Units mm. Printer: Bambu Lab X2D, 0.4 mm nozzle,",
             "textured PEI. See `docs/handoffs/03-printing.md` (coupons first, then parts; Matt starts every print).", "",
             "| Part | Qty | Material | Process | Supports | Slicer overrides | Size (mm) | Verdict | Check warnings |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r[0]}` | {r[8]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} |")
    lines += ["", "Process names map to Bambu Studio presets: `0.12-fine` = 0.12 mm Fine, `0.16-fine` = 0.16 mm Optimal,",
              "`0.20-standard` = 0.20 mm Standard. Materials: Bambu PLA Basic (white) for the moon and step wedge,",
              "Bambu PETG Basic for everything else (it sits next to warm electronics).", "",
              "Moon: 100 % infill + 6 walls makes the lithophane solid; outer brim 3 mm (the skirt ring is the only bed",
              "contact). The inner dome closes over the top as a short bridge - expected; nothing can be supported inside.",
              ""]
    if failed:
        lines.append(f"**Not exported (FAIL):** {', '.join(failed)}")
    (out / "README.md").write_text("\n".join(lines))
    print("exported", [p for p in parts if p not in failed], "listed", [r[0] for r in rows], "failed", failed)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:] or PARTS))
