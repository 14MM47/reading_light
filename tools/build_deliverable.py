def sh(cmd, **kw):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, **kw)
    if r.returncode:
        raise SystemExit(f"command failed: {' '.join(map(str, cmd))}\n{r.stdout}\n{r.stderr}")
    return r.stdout


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


class Builder:
    def __init__(self):
        self.sources: dict[Path, str] = {}      # deliverable path -> source description
        self.md_jobs: list[tuple[Path, Path, str]] = []

    def copy(self, src: Path, dst: Path):
        src = ROOT / src if not src.is_absolute() else src
        if not src.exists():
            raise SystemExit(f"missing source: {src.relative_to(ROOT)} (run the generator that makes it)")
        dst = OUT / dst
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        self.sources[dst] = str(src.relative_to(ROOT))

    def write(self, dst: Path, text: str, source="generated by tools/build_deliverable.py"):
        dst = OUT / dst
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
        self.sources[dst] = source

    def pdf(self, src_md: Path, dst_pdf: Path, title: str):
        """Queue a Markdown -> PDF render (done in one browser session at the end)."""
        src = ROOT / src_md
        if not src.exists():
            raise SystemExit(f"missing source: {src_md}")
        self.md_jobs.append((src, OUT / dst_pdf, title))
        self.sources[OUT / dst_pdf] = f"{src_md} (rendered to PDF)"

    def render_pdfs(self):
        tmp = Path(tempfile.mkdtemp(prefix="deliv_html_"))
        css = tmp / "style.css"
        css.write_text(CSS)
        args = []
        for i, (src, dst, title) in enumerate(self.md_jobs):
            html = tmp / f"{i:03d}.html"
            sh(["pandoc", src, "-f", "gfm", "-t", "html5", "--standalone", "--embed-resources",
                "--resource-path", f"{src.parent}:{ROOT}", "--metadata", f"pagetitle={title}", "-c", css, "-o", html])
            dst.parent.mkdir(parents=True, exist_ok=True)
            args += [html, dst]
        if args:
            sh(["node", ROOT / "tools" / "html2pdf.js", *args], cwd=ROOT,
               env={**os.environ, "DOC_LABEL": f"Moon reading light {BUILD}"})
        shutil.rmtree(tmp)


def board_status(board):
    rep = ROOT / "hardware" / board / "reports"
    drc = json.loads((rep / "drc.json").read_text())
    erc = json.loads((rep / "erc.json").read_text())
    return dict(erc=sum(len(s["violations"]) for s in erc["sheets"]),
                drc_err=sum(v["severity"] == "error" for v in drc["violations"]),
                drc_warn=sum(v["severity"] == "warning" for v in drc["violations"]),
                unconnected=len(drc.get("unconnected_items", [])), parity=len(drc.get("schematic_parity", [])))


def print_rows():
    rows = {}
    for line in (ROOT / "print" / "README.md").read_text().splitlines():
        if line.startswith("| `"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            rows[cells[0].strip("`")] = dict(qty=cells[1], material=cells[2], process=cells[3], supports=cells[4],
                                             overrides=cells[5], size=cells[6], verdict=cells[7])
    return rows


def firmware_hex():
    """Build the four envs with PlatformIO if it is available; otherwise use existing builds if they are current."""
    fw = ROOT / "firmware"
    pio = os.environ.get("PIO") or shutil.which("pio") or shutil.which("platformio")
    if pio:     # PlatformIO's incremental build leaves each hex current with its inputs
        sh([pio, "run", *sum((["-e", e] for _, e, _ in FW_ENVS), [])], cwd=fw)
    inputs = [fw / "platformio.ini"] + [p for d in ("src", "lib", "include") for p in (fw / d).rglob("*") if p.is_file()]
    newest_src = max(p.stat().st_mtime for p in inputs)
    out = {}
    for _, env, _ in FW_ENVS:
        h = fw / ".pio" / "build" / env / "firmware.hex"
        if not h.exists() or (not pio and h.stat().st_mtime < newest_src):
            raise SystemExit(f"firmware hex for {env} missing or older than the sources: set PIO=<path to pio> "
                             "or run `cd firmware && pio run -e <env>` first")
        out[env] = h
    return out


def deterministic_zip(src_dir: Path, zpath: Path, skip=(".pio", "__pycache__", ".vscode")):
    zpath.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(src_dir.rglob("*")):
            if p.is_file() and not any(s in p.parts for s in skip):
                zi = zipfile.ZipInfo(str(p.relative_to(src_dir.parent)), date_time=(2026, 11, 2, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                zi.external_attr = 0o644 << 16
                z.writestr(zi, p.read_bytes())


